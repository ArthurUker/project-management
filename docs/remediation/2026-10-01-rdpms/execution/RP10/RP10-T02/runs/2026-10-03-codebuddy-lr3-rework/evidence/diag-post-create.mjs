import crypto from 'node:crypto';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
const backend = '/Users/renkang/VS Code/project-management/rdpms-system/backend';
const require = createRequire(backend + '/package.json');
const { PrismaClient } = require('@prisma/client');
const { createApp } = await import(pathToFileURL(backend + '/dist/bootstrap/createApp.js'));
const db = new PrismaClient();
const run = crypto.randomUUID();
const user = await db.user.create({ data: { id: `d-${run}`, username: `d-${run}`, displayName: 'D', passwordHash: 'x', systemRole: 'ADMIN', status: 'ACTIVE' } });
const project = await db.project.create({ data: { code: `D-${run}`, name: 'D', type: 'TESTING', status: 'PLANNING', managerId: user.id, createdById: user.id, members: { create: [{ userId: user.id, role: 'OWNER', createdById: user.id }] } } });
const app = createApp({ db, actorResolver: async () => ({ userId: user.id, user, systemRole: 'ADMIN', permissions: ['reports.create', 'reports.update', 'reports.submit', 'reports.delete', 'reports.view'] }) });
const res = await app.request('/api/reports', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ projectId: project.id, reportType: 'MONTHLY', periodKey: '2027-01', content: { r: 1 }, clientMutationId: `k-${run}` }) });
const body = await res.json();
const audits = await db.auditLog.findMany({ select: { action: true, entityId: true } });
const receipts = await db.mutationReceipt.findMany({ select: { command: true, idempotencyKey: true } });
console.log('DIAG ' + JSON.stringify({ status: res.status, id: body.id, audits, receipts }));
await db.$disconnect();
